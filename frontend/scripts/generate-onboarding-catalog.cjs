/**
 * Scan Next.js app routes and emit a typed catalog for onboarding.
 * Copy stays in tourCatalog.ts; this file only lists what exists in the UI tree.
 */
const fs = require("fs");
const path = require("path");

const APP_ROOT = path.join(__dirname, "..", "src", "app");
const OUT = path.join(__dirname, "..", "src", "lib", "onboarding", "generatedRoutes.ts");

const TITLE_BY_PATH = {
  "/": "Dashboard",
  "/account": "Кабинет",
  "/settings": "Настройки",
  "/forecasting": "Forecast",
  "/screener": "Screener",
  "/chat": "AI Chat",
  "/bots": "Bots",
  "/grid": "Grid bots",
  "/dca-bots": "DCA bots",
  "/momentum-bots": "Momentum bots",
  "/direct-deals": "Direct Deals",
  "/portfolio-risk": "Risk",
  "/strategy-composer": "Composer",
  "/terminal": "Terminal",
  "/backtest": "Backtest",
  "/track-record": "Track record",
  "/audit-logs": "Audit logs",
  "/ops/crypto-integrations": "Integrations",
  "/operator/admissions": "Admissions",
};

const SKIP_PREFIX = ["/legal", "/login", "/signup", "/apply", "/legal", "/verify-email", "/recover", "/reset", "/wasnt-me"];

function walk(dir, acc) {
  for (const name of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, name.name);
    if (name.isDirectory()) walk(full, acc);
    else if (name.name === "page.tsx") acc.push(full);
  }
}

function toRoute(file) {
  let rel = path.relative(APP_ROOT, path.dirname(file)).replace(/\\/g, "/");
  if (rel === ".") return "/";
  rel = rel.replace(/\[([^\]]+)\]/g, ":$1");
  return `/${rel}`;
}

function shouldSkip(route) {
  return SKIP_PREFIX.some((p) => route === p || route.startsWith(`${p}/`));
}

const files = [];
walk(APP_ROOT, files);
const routes = [...new Set(files.map(toRoute))]
  .filter((r) => !shouldSkip(r))
  .sort((a, b) => a.localeCompare(b))
  .map((route) => ({
    path: route,
    title: TITLE_BY_PATH[route] || route.split("/").filter(Boolean).pop() || "page",
  }));

const body = `/* Generated by scripts/generate-onboarding-catalog.cjs — do not edit by hand. */
export type GeneratedAppRoute = { path: string; title: string };

export const GENERATED_APP_ROUTES: GeneratedAppRoute[] = ${JSON.stringify(routes, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body, "utf8");
process.stdout.write(`Wrote ${routes.length} routes → ${path.relative(process.cwd(), OUT)}\n`);
